// --- Helpers ---
export function hitungUsiaBulan(
  tanggalLahir: string,
  tanggalAcuan = new Date(),
): number {
  const lahir = new Date(tanggalLahir);
  const diff = tanggalAcuan.getTime() - lahir.getTime();
  return Math.max(0, Math.floor(diff / (1000 * 60 * 60 * 24 * 30.4375)));
}

export function formatTanggalID(iso: string): string {
  const bulan = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "Mei",
    "Jun",
    "Jul",
    "Agu",
    "Sep",
    "Okt",
    "Nov",
    "Des",
  ];
  const d = new Date(iso);
  return `${d.getDate()} ${bulan[d.getMonth()]} ${d.getFullYear()}`;
}

export function formatTanggalPanjangID(iso: string): string {
  const bulan = [
    "Januari",
    "Februari",
    "Maret",
    "April",
    "Mei",
    "Juni",
    "Juli",
    "Agustus",
    "September",
    "Oktober",
    "November",
    "Desember",
  ];
  const d = new Date(iso);
  return `${d.getDate()} ${bulan[d.getMonth()]} ${d.getFullYear()}`;
}

