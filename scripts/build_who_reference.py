def format_table(name: str, table: dict[int, tuple[float, float, float]]) -> str:
    out = [f"const {name}: Record<number, [number, number, number]> = {{"]
    for k in sorted(table.keys()):
        L, M, S = table[k]
        # Trim trailing zeros for readability, keep up to 4 decimals
        def fmt(x: float) -> str:
            s = f"{x:.4f}".rstrip("0").rstrip(".")
            return s if s else "0"
        out.append(f"  {k}: [{fmt(L)}, {fmt(M)}, {fmt(S)}],")
    out.append("};")
